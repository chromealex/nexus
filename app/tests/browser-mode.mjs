import assert from 'node:assert/strict';
import {BROWSER_MODES, browserSummary, browserHint, browserRequest} from '../src/browser-mode.js';
assert.deepEqual(Object.keys(BROWSER_MODES), ['off', 'isolated', 'chrome']);
assert.equal(browserSummary('off'), '');
assert.equal(browserSummary('isolated'), 'Браузер');
assert.equal(browserSummary('chrome'), 'Мой Chrome');
const ready = {installed: true, node: true, chrome: true, version: '0.0.85'};
assert.equal(browserHint('off', {}).action, undefined);
assert.equal(browserHint('isolated', {...ready, installed: false}).action, 'install');
assert.match(browserHint('isolated', {...ready, installed: false}).text, /0\.0\.85/);
assert.equal(browserHint('isolated', {...ready, node: false}).tone, 'warn');
assert.match(browserHint('isolated', {...ready, node: false}).text, /Node/);
assert.match(browserHint('chrome', {...ready, chrome: false}).text, /Chrome/);
assert.equal(browserHint('chrome', ready).action, 'extension');
assert.match(browserHint('chrome', ready).text, /недоступно/);
assert.equal(browserHint('isolated', ready).tone, 'info');
assert.equal(browserHint('isolated', {...ready, installing: true}).action, undefined);
const own = browserRequest({mode: 'chrome', summary: 'Нажать «Купить»', host: 'shop.example'});
assert.ok(own.own);
assert.match(own.where, /Chrome/);
assert.equal(own.host, 'shop.example');
assert.equal(browserRequest({tool: 'browser_click'}).summary, 'browser_click');
assert.ok(!browserRequest({mode: 'isolated'}).own);
console.log('browser-mode tests passed');
