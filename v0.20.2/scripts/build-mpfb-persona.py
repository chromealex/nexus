"""Build a full 3D head cloud directly from MPFB's CC0 mesh and target assets.
No addon code is executed. Run from v0.20.2 with the official archive in its parent.
Layout: position/color/seed/size/layer/blink delta/smile delta/normal (18 floats).
"""
import zipfile,gzip,math,random,struct,bisect,json,hashlib
from pathlib import Path
archive=Path('../add-on-mpfb-v2.0.18.zip');z=zipfile.ZipFile(archive)
source=z.read('data/3dobjs/base.obj').decode();verts=[];faces=[];group=''
for line in source.splitlines():
 if line.startswith('v '):verts.append(list(map(float,line.split()[1:4])))
 elif line.startswith('g '):group=line[2:]
 elif line.startswith('f ') and group=='body':
  ids=[int(x.split('/')[0])-1 for x in line.split()[1:]]
  for i in range(1,len(ids)-1):faces.append((ids[0],ids[i],ids[i+1]))
def target(name):
 result=[[0.,0.,0.] for _ in verts]
 for line in gzip.decompress(z.read('data/targets/'+name+'.target.gz')).decode().splitlines():
  if not line or line.startswith('#'):continue
  i,*xyz=line.split();result[int(i)]=list(map(float,xyz))
 return result
for name in ['macrodetails/caucasian-female-young','macrodetails/universal-female-young-averagemuscle-averageweight']:
 for v,d in zip(verts,target(name)):
  for k in range(3):v[k]+=d[k]
# Additional authored proportions on the supplied female phenotype.
for name,weight in [('head/head-oval',.35),('chin/chin-width-decr',.35),('chin/chin-bones-decr',.30),('chin/chin-prominent-decr',.15),('nose/nose-scale-horiz-decr',.15),('mouth/mouth-upperlip-volume-incr',.25),('mouth/mouth-lowerlip-volume-incr',.20)]:
 for v,d in zip(verts,target(name)):
  for k in range(3):v[k]+=d[k]*weight
smile=target('mouth/mouth-angles-up');blink=[[0.,0.,0.] for _ in verts]
# Use shipped eye-height morph deltas, combined for both eyes; not a full expression pack.
for side in ['l','r']:
 for section in [1,2,3]:
  for b,d in zip(blink,target(f'eyes/{side}-eye-height{section}-decr')):
   for k in range(3):b[k]+=d[k]*1.5
# Crop below clavicle. No helper/rig/proxy geometry is rendered.
faces=[f for f in faces if min(verts[i][1] for i in f)>4.65]
scale=.46; cy=6.23;cz=.45
vout=[(v[0]*scale,(v[1]-cy)*scale,(v[2]-cz)*scale) for v in verts]
# Keep the real mesh for inspection and later replacement of facial morphs.
used=sorted(set(i for f in faces for i in f));mapping={v:i+1 for i,v in enumerate(used)}
out=Path('public/persona');out.mkdir(exist_ok=True)
(out/'makehuman-head.obj').write_text('# MakeHuman CC0 female head and shoulders; generated by Nexus\n'+''.join('v %.6f %.6f %.6f\n'%vout[i] for i in used)+''.join('f %d %d %d\n'%tuple(mapping[i] for i in f) for f in faces))
tris=[];cumulative=[];total=0
for f in faces:
 a,b,c=[vout[i] for i in f];u=[b[k]-a[k] for k in range(3)];v=[c[k]-a[k] for k in range(3)];n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]];length=math.sqrt(sum(t*t for t in n))
 if length<1e-10:continue
 total+=length*.5;cumulative.append(total);tris.append((f,[x/length for x in n]))
rng=random.Random(319);points=[]
for _ in range(110000):
 f,n=tris[bisect.bisect_left(cumulative,rng.random()*total)]
 r=math.sqrt(rng.random());s=rng.random();weights=[1-r,r*(1-s),r*s]
 def interpolate(values):return [sum(weights[j]*values[f[j]][k] for j in range(3)) for k in range(3)]
 p=interpolate(vout);bd=[x*scale for x in interpolate(blink)];sd=[x*scale for x in interpolate(smile)]
 # Small sparse warm sparks within silver/cyan cloud, not baked photographic illumination.
 warm=rng.random()>.992;rgb=[.86,.65,.36] if warm else [.55,.80,.86]
 points.extend(p+rgb+[rng.random(),.45+rng.random()**3*1.6,0]+bd+sd+n)
# Procedural 3D hair strands fitted around the actual skull; separate from floor layer.
for strand in range(680):
 a=rng.random()*math.tau
 front=math.cos(a)>.38
 end=.82 if front else 1.45
 length=0 if front else .65+rng.random()*.35
 phase=rng.random()*math.tau
 for j in range(95):
  t=j/94
  if t<.53 or front:
   theta=(t/.53 if not front else t)*end
   x=.405*math.sin(theta)*math.sin(a)
   y=.39+.465*math.cos(theta)
   zz=.035+.415*math.sin(theta)*math.cos(a)
  else:
   down=(t-.53)/.47
   x=.405*math.sin(end)*math.sin(a)+math.sin(down*6+phase)*.025*down
   y=.39+.465*math.cos(end)-down*length
   zz=.035+.415*math.sin(end)*math.cos(a)+math.sin(down*5+phase)*.035*down
  x+=rng.uniform(-.006,.006);y+=rng.uniform(-.003,.003);zz+=rng.uniform(-.006,.006)
  n=[math.sin(a),.2,math.cos(a)];norm=math.sqrt(sum(k*k for k in n));n=[k/norm for k in n]
  warm=strand%43==0;rgb=[.88,.66,.39] if warm else [.63,.86,.92]
  points.extend([x,y,zz]+rgb+[rng.random(),.45+rng.random()*.7,2]+[0]*6+n)
for _ in range(3200):
 a=rng.random()*math.tau;r=math.sqrt(rng.random())*1.1
 points.extend([math.cos(a)*r,-.79+rng.random()**3*.08,math.sin(a)*r*.38,.43,.76,.86,rng.random(),.65+rng.random()**4*3.2,1]+[0]*6+[0,1,0])
assert all(math.isfinite(x) for x in points)
(out/'makehuman-head.points').write_bytes(struct.pack('<'+'f'*len(points),*points))
meta={'source':'MPFB 2.0.18 / MakeHuman hm08','license':'CC0-1.0','archiveSha256':hashlib.sha256(archive.read_bytes()).hexdigest(),'pointCount':len(points)//18,'strideFloats':18,'triangles':len(faces),'vertices':len(used),'morphs':{'blink':'combined shipped eye-height decrease targets','smile':'shipped mouth-angles-up target'},'limitations':['Hair is custom procedural strands fitted to the skull','No full FACS/ARKit expression pack or lip-sync']}
(out/'makehuman-head.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2))
(out/'SOURCES.md').write_text('''# Persona sources

MakeHuman hm08 mesh and bundled target assets from the user-supplied official MPFB 2.0.18 archive. Mesh header explicitly dedicates this asset to CC0 (September 2020).
Copyright holders at dedication: Data Collection AB, Joel Palmius, Jonas Hauquier.
https://www.makehumancommunity.org/about/license.html
https://github.com/makehumancommunity/makehuman/blob/master/LICENSE.ASSETS.md

Nexus modifications: female phenotype, head/clavicle crop, area-weighted surface sampling, combined eyelid and mouth morphs, cyan point shading. No MPFB application code is shipped in Nexus.
Environment PNG: generated for this project, separate from the model.
''')
print(json.dumps(meta,indent=2))
