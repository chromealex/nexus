import assert from 'node:assert/strict';
import {shortcutFor} from '../src/shortcuts.js';

const ev=(key,extra={})=>({key,code:'',metaKey:false,ctrlKey:false,altKey:false,shiftKey:false,isComposing:false,...extra});
assert.equal(shortcutFor(ev('n',{metaKey:true}),true),'newChat');
assert.equal(shortcutFor(ev('K',{metaKey:true}),true),'search','case-insensitive');
assert.equal(shortcutFor(ev('т',{metaKey:true,code:'KeyN'}),true),'newChat','Cyrillic layout uses physical key');
assert.equal(shortcutFor(ev(',',{metaKey:true}),true),'connections');
assert.equal(shortcutFor(ev('/',{metaKey:true}),true),'model');
assert.equal(shortcutFor(ev('[',{metaKey:true}),true),'previous');
assert.equal(shortcutFor(ev(']',{metaKey:true}),true),'next');
assert.equal(shortcutFor(ev('\\',{metaKey:true}),true),'sidebar');
assert.equal(shortcutFor(ev('n'),true),null,'no modifier');
assert.equal(shortcutFor(ev('n',{ctrlKey:true}),true),null,'Ctrl is not ⌘ on macOS');
assert.equal(shortcutFor(ev('n',{metaKey:true,shiftKey:true}),true),null,'Shift chords are left to the system');
assert.equal(shortcutFor(ev('n',{metaKey:true,altKey:true}),true),null);
assert.equal(shortcutFor(ev('n',{metaKey:true,isComposing:true}),true),null,'IME composition is ignored');
assert.equal(shortcutFor(ev('n',{ctrlKey:true}),false),'newChat','Ctrl on other systems');
assert.equal(shortcutFor(ev('x',{metaKey:true}),true),null,'unknown keys pass through (⌘X, ⌘C, ⌘V)');
console.log('Shortcuts: modifiers, Cyrillic layout, IME and passthrough of system chords passed.');
